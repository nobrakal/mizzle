#!/usr/bin/env python3
"""Regenerate the API cards of the proof guides.

Each card lists, verbatim, the statements of the lemmas whose doc comment
carries the token [[card]] in the files scanned for that guide: the by-hand
interface as the library itself declares it. Run this after changing any
of them.

Usage: gen_api_card.py [--check]
  --check   exit 1 if a guide is out of date instead of rewriting it
"""

import os
import re
import sys

ROOT = os.path.dirname(os.path.abspath(__file__))
BEGIN = "<!-- API CARD: generated by gen_api_card.py, do not edit -->"
END = "<!-- END API CARD -->"

# Guide -> files scanned for its card entries: any Lemma/Definition whose
# doc comment, immediately above it, contains the token [[card]]. A card is
# therefore the library's own declaration of its by-hand interface, in file
# order.
GUIDES = {
    "src/dataracebench/support/PROOF_GUIDE.md": [
        "src/stdlib/array.v",
        "src/logic/goal_tactics.v",
        "src/dataracebench/support/drb_axiom.v",
        "src/stdlib/structeq.v",
        "src/logic/race.v",
        "src/logic/interp.v",
    ],
    "src/linearizable/support/PROOF_GUIDE.md": [
        "src/stdlib/rand.v",
        "src/logic/most_general_client.v",
        "src/logic/adequacy_lin.v",
        "src/pure_logic/linear.v",
        "src/pure_logic/linear_check.v",
        "src/linearizable/support/htbl_array.v",
        "src/logic/interp.v",
    ],
}
MARK = "[[card]]"

# A header may be indented (inside a Section); the statement is dedented.
HEAD_RE = r"^\s*(Lemma|Theorem|Corollary|Axiom|Definition|Fixpoint)\s+{}\b"
HEAD_ANY = re.compile(r"^\s*(Lemma|Theorem|Corollary|Axiom|Definition|Fixpoint)\s+(\S+)")


def marked(path):
    """Names in PATH whose immediately preceding doc comment holds MARK."""
    with open(os.path.join(ROOT, path), encoding="utf-8") as f:
        lines = f.read().split("\n")
    names = []
    for i, line in enumerate(lines):
        m = HEAD_ANY.match(line)
        if not m:
            continue
        j = i - 1
        while j >= 0 and not lines[j].strip():
            j -= 1
        if j >= 0 and lines[j].rstrip().endswith("*)"):
            k = j
            while k >= 0 and "(*" not in lines[k]:
                k -= 1
            if k >= 0 and "(**" in lines[k] and MARK in "\n".join(lines[k:j + 1]):
                names.append(m.group(2))
    return names


def card(scan):
    return [(path, name) for path in scan for name in marked(path)]



def statement(path, name):
    """The statement of NAME in PATH: from its header line up to (excluding)
    `Proof`, or, for a Definition/Axiom, through the line ending the sentence."""
    with open(os.path.join(ROOT, path), encoding="utf-8") as f:
        lines = f.read().split("\n")
    head = re.compile(HEAD_RE.format(re.escape(name)))
    for i, line in enumerate(lines):
        if not head.match(line):
            continue
        out = []
        kind = line.lstrip().split()[0]
        for l in lines[i:]:
            if re.match(r"^\s*Proof\b", l):
                break
            out.append(l.rstrip())
            if l.rstrip().endswith(".") and kind in ("Definition", "Fixpoint",
                                                     "Axiom"):
                break
        while out and not out[-1].strip():
            out.pop()
        indent = len(line) - len(line.lstrip())
        return "\n".join(l[indent:] if l[:indent].strip() == "" else l
                         for l in out)
    sys.exit(f"gen_api_card: {name} not found in {path}")


def render(scan):
    blocks = []
    for path, name in card(scan):
        blocks.append(f"`{path}`\n\n```coq\n{statement(path, name)}\n```")
    return BEGIN + "\n\n" + "\n\n".join(blocks) + "\n\n" + END


def update(guide_rel, scan, check):
    """Rewrite (or, with CHECK, verify) the card of GUIDE_REL; the exit status."""
    guide_path = os.path.join(ROOT, guide_rel)
    with open(guide_path, encoding="utf-8") as f:
        guide = f.read()
    b, e = guide.find(BEGIN), guide.find(END)
    if b < 0 or e < 0:
        sys.exit(f"gen_api_card: markers not found in {guide_rel}")
    new = guide[:b] + render(scan) + guide[e + len(END):]
    if new == guide:
        return 0
    if check:
        print(f"gen_api_card: {guide_rel} API card is out of date")
        return 1
    with open(guide_path, "w", encoding="utf-8") as f:
        f.write(new)
    print(f"gen_api_card: rewrote API card in {guide_rel}")
    return 0


def main():
    check = "--check" in sys.argv[1:]
    return max(update(guide, scan, check) for guide, scan in GUIDES.items())


if __name__ == "__main__":
    sys.exit(main())
