Lemma per_tag_partial_linearized_filter_call τ v ts :
  per_tag_partial_linearized ((τ,Call v) :: ts) →
  filter (λ t, t.1 = τ) ts = [] ∨
  ∃ v' xs, filter (λ t, t.1 = τ) ts = (τ,Lin v v')::xs.
Proof.
  intros Hlin.
  destruct (Hlin τ) as (v_ & v' & Hsubstr).
  rewrite filter_cons_True // in Hsubstr.
  destruct (filter (λ t, t.1 = τ) ts) as [|ts_hd xs] eqn:Heq.
  - left; done.
  - right. exists v', xs.
    destruct Hsubstr as (l1 & l2 & Hsubstr).
    destruct l1 as [|? l1]; last first.
    { (* impossible *)
      assert (length l1 = 0 ∧ length xs = 0 ∧ length l2 = 0) as (?&?&?).
      { apply (f_equal length) in Hsubstr.
      rewrite !length_app /= in Hsubstr. lia. }
      destruct l1; last done.
      destruct xs; last done.
      destruct l2; last done.
      rewrite right_id_L /= in Hsubstr.
      injection Hsubstr as ? HFalse.
      discriminate HFalse. }
    rewrite left_id_L -!app_comm_cons in Hsubstr.
    injection Hsubstr as Hcall_eq Hlin_eq Hret_eq.
    by simplify_eq.
Qed.

Lemma per_tag_partial_linearized_filter_lin τ v v' ts :
  per_tag_partial_linearized ((τ, Lin v v') :: ts) →
  filter (λ t, t.1 = τ) ts = [] ∨
  filter (λ t, t.1 = τ) ts = [(τ,Ret v')].
Proof.
  intros Hlin.
  destruct (Hlin τ) as (v_ & v'_ & Hsubstr).
  rewrite filter_cons_True // in Hsubstr.
  destruct (filter (λ t, t.1 = τ) ts) as [|ts_hd xs] eqn:Heq.
  - left; done.
  - right.
    destruct Hsubstr as (l1 & l2 & Hsubstr).
    destruct l1 as [|? l1].
    { (* impossible *)
      rewrite left_id_L -!app_comm_cons in Hsubstr.
      injection Hsubstr as HFalse.
      discriminate HFalse. }
    assert (length l1 = 0 ∧ length xs = 0 ∧ length l2 = 0) as (?&?&?).
    { apply (f_equal length) in Hsubstr.
      rewrite !length_app /= in Hsubstr. lia. }
    destruct l1; last done.
    destruct xs; last done.
    destruct l2; last done.
    rewrite right_id_L /= in Hsubstr.
    by simplify_eq.
Qed.

Lemma per_tag_partial_linearized_filter_ret τ v ts :
