Definition pendingOp : Set := positive * option expr.

Definition pendingOp_active (π : list pendingOp) : list (positive * expr) :=
  omap (λ '(τ, oe), match oe with Some e => Some (τ, e) | None => None end) π.

Lemma pendingOp_active_nil : pendingOp_active [] = [].
Proof. done. Qed.

Lemma pendingOp_active_cons_Some τ e π :
  pendingOp_active ((τ, Some e) :: π) = (τ, e) :: pendingOp_active π.
Proof. done. Qed.

Lemma pendingOp_active_cons_None τ π :
  pendingOp_active ((τ, None) :: π) = pendingOp_active π.
Proof. done. Qed.

Lemma pendingOp_active_app π₁ π₂ :
  pendingOp_active (π₁ ++ π₂) = pendingOp_active π₁ ++ pendingOp_active π₂.
Proof. apply omap_app. Qed.

Lemma pendingOp_active_snoc_Some τ e π :
  pendingOp_active (π++[(τ, Some e)]) = pendingOp_active π++[(τ, e)].
Proof. rewrite pendingOp_active_app //. Qed.

Lemma pendingOp_active_snoc_None τ π :
  pendingOp_active (π++[(τ, None)]) = pendingOp_active π.
Proof. rewrite pendingOp_active_app pendingOp_active_cons_None /= right_id_L //. Qed.

Lemma not_elem_of_pendingOp_active_fmap τ π :
  τ ∉ π.*1 → τ ∉ (pendingOp_active π).*1.
Proof.
  induction π as [|[τ' [e|]] π IH]; simpl; first done.
  - rewrite !not_elem_of_cons. intros [? ?]. split; first done. by apply IH.
  - intros Hnotin. apply IH. set_solver.
Qed.

Lemma elem_of_pendingOp_active_split τ e π :
  (τ, e) ∈ pendingOp_active π →
  ∃ π₁ π₂, π = π₁ ++ (τ, Some e) :: π₂.
Proof.
  induction π as [|[τ' [e'|]] π IH]; simpl.
  - intros []%not_elem_of_nil.
  - rewrite elem_of_cons. intros [[= -> ->] | Hin].
    + exists [], π. done.
    + destruct (IH Hin) as (π₁ & π₂ & ->).
      exists ((τ', Some e') :: π₁), π₂. done.
  - intros Hin. destruct (IH Hin) as (π₁ & π₂ & ->).
    exists ((τ', None) :: π₁), π₂. done.
Qed.

Record configuration := Config {
  config_pendingOp : list pendingOp;
  config_childThread : list expr;
  config_state : state;
}.

Section adv_step.
  Context (op obj : val) (valid_request : val → Prop).
  Implicit Types (τ : positive) (π : list pendingOp) (σ : state) (e : expr) (v : val).

  (* A possible behavior of an object with a most adversarial client. *)
  (* A most adversarial client repeatedly concurrently invokes an object with
    (demonically) non-determinitic request values. It covers all possible
    usages of a library that do not break the abstraction of the library. *)
  Inductive adv_step : configuration → configuration → list (positive*trace) → Prop :=
    | adv_step_call v τ π efs σ :
      τ ∉ π.*1 → valid_request v →
      adv_step (Config π efs σ) (Config (π++[(τ,Some (op obj v))]) efs σ) [(τ,Call v)]
    | adv_step_intermediate τ π₁ π₂ efs e e' σ σ' κ ef tid :
      prim_step tid e σ κ e' σ' ef →
      adv_step (Config (π₁++(τ,Some e)::π₂) efs σ) (Config (π₁++(τ,Some e')::π₂) (efs++ef) σ') []
    | adv_step_child π efs1 efs2 e e' σ σ' κ ef tid :
      prim_step tid e σ κ e' σ' ef →
      adv_step (Config π (efs1++e::efs2) σ) (Config π (efs1++e'::efs2++ef) σ') []
    | adv_step_return τ π₁ π₂ efs v σ :
      adv_step (Config (π₁++(τ,Some (Val v))::π₂) efs σ) (Config (π₁++(τ,None)::π₂) efs σ) [(τ,Ret v)].

  Inductive adv_steps : configuration → configuration → list (positive*trace) → Prop :=
    | adv_steps_nil config : adv_steps config config []
    | adv_steps_cons config0 config1 config2 ts1 ts2 :
      adv_step config0 config1 ts1 →
      adv_steps config1 config2 ts2 →
      adv_steps config0 config2 (ts1++ts2).

  Definition config_no_fork (config : configuration) : Prop :=
    config.(config_childThread) = [].

  (** [not_stuck] in MizzleLang takes a [tid]; for [config_not_stuck], use the
      pending-op slot's index in [π] (resp. its index in the child-thread
      list) as the [tid]. *)
  Definition config_not_stuck (config : configuration) : Prop :=
    Foralli (λ tid p, match p.2 with Some e => not_stuck tid e config.(config_state) | None => True end) config.(config_pendingOp)
    ∧ Foralli (λ tid e, not_stuck (length config.(config_pendingOp) + tid) e config.(config_state)) config.(config_childThread).
End adv_step.

Definition library_initializable (init : val) (valid_obj : val → state → Prop) :=
  ∀ σ, adequate_nofork (init ()%E) σ valid_obj.

Definition library_linearizable `{M : model} (op : val) (valid_obj : val → state → Prop) :=
  ∀ obj σ config' ts, valid_obj obj σ →
    adv_steps op obj valid_request (Config [] [] σ) config' ts →
    config_not_stuck config' ∧ trace_linearizable ts.

Definition library_initializable_linearizable `{M : model} (init op : val) :=
  (∀ σ, adequate_nofork (init ()%E) σ (λ _ _, True)) ∧
  (∀ obj σ₀ σ config' ts,
    rtc silent_step ([init ()%E], σ₀) ([Val obj], σ) →
    adv_steps op obj valid_request (Config [] [] σ) config' ts →
    config_not_stuck config' ∧ trace_linearizable ts).

Definition config_safe `{M : model} (op : val) obj π efs σ :=
  ∀ config' ts, adv_steps op obj valid_request (Config π efs σ) config' ts →
  config_not_stuck config'.

Lemma pendingOp_nodup_inj (τ : positive) (π₁ : list pendingOp) (e : option expr) π₂ π₁' (e' : option expr) π₂' :
  NoDup (π₁++(τ,e)::π₂).*1 →
  π₁++(τ,e)::π₂ = π₁'++(τ,e')::π₂' →
  π₁ = π₁' ∧ e = e' ∧ π₂ = π₂'.
Proof.
  intros Hnodup Heq.
  destruct (decide (length π₁ = length π₁')).
  - apply app_inj_1 in Heq as [? Heq]; last done.
    injection Heq as ? ?.
    done.
  - apply (f_equal (λ x, x !! length π₁')) in Heq.
    rewrite (lookup_app_r π₁') // Nat.sub_diag -head_lookup /= in Heq.
    destruct (decide (length π₁ ≤ length π₁')).
    + rewrite cons_middle assoc in Heq.
      rewrite lookup_app_r in Heq; last (rewrite length_app /=; lia).
      apply take_drop_middle in Heq.
      rewrite -Heq in Hnodup.
      do 2 rewrite fmap_app fmap_cons /= in Hnodup.
      rewrite NoDup_app in Hnodup. destruct Hnodup as (_&_&Hnodup).
      rewrite NoDup_cons in Hnodup. destruct Hnodup as [Hnodup _].
      destruct Hnodup. set_solver.
    + rewrite lookup_app_l in Heq; last lia.
      apply take_drop_middle in Heq.
      rewrite -Heq in Hnodup.
      rewrite !fmap_app !fmap_cons /= in Hnodup.
      rewrite NoDup_app in Hnodup.
      destruct Hnodup as (_&Hnodup&_).
      destruct (Hnodup τ); set_solver.
Qed.

