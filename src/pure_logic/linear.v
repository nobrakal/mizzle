Definition trace_linearizable `{M : model} ts :=
  (* call_valid prevents an edge case: an op is called with
    an invalid operand, but this op never returns *)
  call_valid ts ∧
  ∃ ts', ts = filter (not ∘ is_lin ∘ snd) ts'
      ∧ per_tag_linearized ts'
      ∧ ∃ s', linearized_sound (filter (is_lin ∘ snd) ts') s_init s'.

(** A trace is non-linearizable if all its calls are valid and it is not
  linearizable. Without call_valid, any trace with an invalid call would
  trivially be non-linearizable. [[card]] *)
Definition trace_non_linearizable `{M : model} ts :=
  call_valid ts ∧ ¬ trace_linearizable ts.

Section trace_linearizable_facts.
  Context `{M : model}.

  Lemma trace_linearizable_nil :
    trace_linearizable [].
  Proof.
    split; first rewrite /call_valid //.
    exists []. split; last split.
    - rewrite filter_nil //.
    - apply per_tag_linearized_nil.
    - exists s_init. apply linearized_sound_nil.
  Qed.

  Lemma trace_linearizable_prefix ts1 ts2 :
    ts1 `prefix_of` ts2 →
    trace_linearizable ts2 →
    trace_linearizable ts1.
  Proof.
    intros [ts3 ->] (Hcall_valid & ts13' & Hfilter & Hper_tag_lin & Hlin_sound).
    apply filter_app_inv in Hfilter as (ts1' & ts3' & -> & Hfilter1 & Hfilter3).
    split.
    { rewrite /call_valid Forall_app in Hcall_valid. by destruct Hcall_valid. }
    exists ts1'. split; first done.
    split.
    - intros τ. destruct (Hper_tag_lin τ) as (v & v' & Hprefix).
      exists v, v'.
      rewrite filter_app in Hprefix.
      by eapply prefix_app_l.
    - eapply linearized_sound_prefix; last eassumption.
      rewrite filter_app. by apply prefix_app_r.
  Qed.

  Lemma trace_linearizable_per_tag_wellformed ts :
    trace_linearizable ts → per_tag_wellformed ts.
  Proof.
    intros [_ (ts' & -> & Hper_tag_lin & _)] τ.
    destruct (Hper_tag_lin τ) as (v & v' & Hprefix).
    exists v, v'.
    rewrite list_filter_comm.
    apply (prefix_filter (not ∘ is_lin ∘ snd)) in Hprefix.
    rewrite filter_cons_True in Hprefix; last compute_done.
    rewrite filter_cons_False in Hprefix; last compute_done.
    rewrite filter_cons_True in Hprefix; last compute_done.
    rewrite filter_nil in Hprefix.
    done.
  Qed.
End trace_linearizable_facts.

