Lemma adv_steps_app op obj valid_request config0 config1 config2 ts1 ts2 :
  adv_steps op obj valid_request config0 config1 ts1 →
  adv_steps op obj valid_request config1 config2 ts2 →
  adv_steps op obj valid_request config0 config2 (ts1++ts2).
Proof.
  intros Hstep1.
  induction Hstep1 => Hstep2; first rewrite left_id //.
  rewrite -assoc.
  eapply adv_steps_cons; eauto.
Qed.

Lemma adv_steps_cons_inj op obj valid_request config config' t ts :
  adv_steps op obj valid_request config config' (t::ts) →
  ∃ config_mid, adv_steps op obj valid_request config config_mid [t]
    ∧ adv_steps op obj valid_request config_mid config' ts.
Proof.
  intros Hadv_steps. remember (t::ts) as ts0 eqn:Heqts0.
  induction Hadv_steps as [|config0 config1 config2 ts1 ts2 Hadv_step Hadv_steps IH]; first done.
  destruct Hadv_step eqn:Heq.
  - (* Call *)
    injection Heqts0 as <- ->.
    eexists. split; last eassumption.
    rewrite -(right_id [] (++) [(_,Call _)]).
    eapply adv_steps_cons; last apply adv_steps_nil.
    assumption.
  - (* Intermediate *)
    rewrite left_id in Heqts0.
    destruct (IH Heqts0) as (config_mid & Hadv_steps0 & Hadv_steps1).
    exists config_mid. split; [|done].
    rewrite -(left_id [] (++) [t]).
    eapply adv_steps_cons; last eassumption.
    by eapply adv_step_intermediate.
  - (* Child *)
    rewrite left_id in Heqts0.
    destruct (IH Heqts0) as (config_mid & Hadv_steps0 & Hadv_steps1).
    exists config_mid. split; [|done].
    rewrite -(left_id [] (++) [t]).
    eapply adv_steps_cons; last eassumption.
    by eapply adv_step_child.
  - (* Return *)
    injection Heqts0 as <- ->.
    eexists. split; last eassumption.
    rewrite -(right_id [] (++) [(_,Ret _)]).
    eapply adv_steps_cons; last apply adv_steps_nil.
    assumption.
Qed.

Lemma adv_steps_app_inj op obj valid_request config config' ts1 ts2 :
  adv_steps op obj valid_request config config' (ts1++ts2) →
  ∃ config_mid, adv_steps op obj valid_request config config_mid ts1
    ∧ adv_steps op obj valid_request config_mid config' ts2.
Proof.
  revert config config'.
  induction ts1 as [|t1 ts1 IH] => config config'.
  - rewrite left_id => Hadv_step.
    exists config. split; last assumption.
    apply adv_steps_nil.
  - rewrite -app_comm_cons => Hadv_step.
    apply adv_steps_cons_inj in Hadv_step.
    destruct Hadv_step as (config1 & Hadv_step0 & Hadv_step1).
    apply IH in Hadv_step1.
    destruct Hadv_step1 as (config2 & Hadv_step1 & Hadv_step2).
    exists config2. split; last assumption.
    change (t1::ts1) with ([t1]++ts1).
    by eapply adv_steps_app.
Qed.

(** MizzleLang doesn't ship the monotonicity lemmas
    [prim_step_heap_subdom] that the
    heap_lang version of these proofs relied on. We prove MizzleLang
    analogues here by case analysis on [base_step], then lift to
    [prim_step] (which is just [base_step] under an evaluation
    context). *)

Lemma base_step_state_heap_dom_subset tid e1 σ1 κ e2 σ2 es :
  base_step tid e1 σ1 κ e2 σ2 es →
  dom σ1.(state_heap) ⊆ dom σ2.(state_heap).
Proof.
  induction 1; rewrite ?/state_alloc ?/state_set_location ?/state_set_local
    ?/state_add_local /=; try done.
  - rewrite dom_union_L. set_solver.
  - rewrite dom_union_L. set_solver.
  - apply dom_insert_subseteq.
  - apply dom_insert_subseteq.
  - apply dom_insert_subseteq.
  - apply dom_insert_subseteq.
Qed.

Lemma prim_step_state_heap_dom_subset tid e1 σ1 κ e2 σ2 es :
  prim_step tid e1 σ1 κ e2 σ2 es →
  dom σ1.(state_heap) ⊆ dom σ2.(state_heap).
Proof.
  intros [K e1' e2' -> -> Hbase].
  by eapply base_step_state_heap_dom_subset.
Qed.

Lemma adv_step_heap_subdom op obj valid_request config config' ts :
  adv_step op obj valid_request config config' ts →
  dom (config.(config_state).(state_heap)) ⊆ dom (config'.(config_state).(state_heap)).
Proof.
  intros Hadv_step. inversion Hadv_step; simplify_eq; simpl; [done| | |done];
  by eapply prim_step_state_heap_dom_subset.
Qed.

Lemma adv_steps_heap_subdom op obj valid_request config config' ts :
  adv_steps op obj valid_request config config' ts →
