Lemma library_initializable_linearizable_destruct `{M : model} init op :
  library_initializable_linearizable init op →
  ∃ valid_obj, library_initializable init valid_obj ∧ library_linearizable op valid_obj.
Proof.
  intros [Hadq Hlin].
  exists (λ op σ, ∃ σ₀, rtc silent_step ([init ()%E], σ₀) ([Val op], σ)).
  split.
  - intros σ₀. specialize (Hadq σ₀). constructor.
    + eapply adequate_nofork_nofork. eassumption.
    + intros t2 σ2 v2 Hsteps. exists σ₀.
      eapply adequate_nofork_nofork in Hadq; last exact Hsteps.
      destruct t2; simpl in Hadq; last lia.
      exact Hsteps.
    + eapply adequate_nofork_not_stuck. eassumption.
  - intros obj σ config' ts [σ₀ Hsteps] Hadv_steps.
    eauto.
Qed.

Lemma library_initializable_linearizable_combine `{M : model} init op valid_obj :
  library_initializable init valid_obj → library_linearizable op valid_obj →
  library_initializable_linearizable init op.
Proof.
  intros Hinit Hop. split.
  - intros σ. destruct (Hinit σ). constructor; eauto.
  - intros obj σ₀ σ config' ts Hsteps Hadv_steps.
    eapply Hop; last eassumption.
    destruct (Hinit σ₀). eauto.
Qed.

Lemma library_initializable_linearizable_iff `{M : model} init op :
  library_initializable_linearizable init op ↔
  ∃ valid_obj, library_initializable init valid_obj ∧ library_linearizable op valid_obj.
Proof.
  split.
  - apply library_initializable_linearizable_destruct.
  - intros (?&?&?). eapply library_initializable_linearizable_combine; eassumption.
Qed.

(** ** Stripping value prefixes from [adv_step]/[adv_steps] children ******

    A leading [Val w] in [efs] cannot be touched by any [adv_step] (no
    rule fires on values), so it is preserved through any trajectory.
    Both directions are useful when bridging a program's output
    (which has the init-phase result threaded through children) to
    [library_initializable_linearizable]'s expected [Config [] [] σ]
    form. *)

Lemma adv_step_drop_value_one_prefix (op obj : val) (valid_request : val → Prop)
    (w : val) π efs σ config' ts :
  adv_step op obj valid_request (Config π (Val w :: efs) σ) config' ts →
  ∃ efs', config'.(config_childThread) = Val w :: efs' ∧
    adv_step op obj valid_request (Config π efs σ)
      (Config config'.(config_pendingOp) efs' config'.(config_state)) ts.
Proof.
  intros Hstep. inversion Hstep; subst.
  - (* adv_step_call *)
    eexists efs. cbn. split; first done. by apply adv_step_call.
  - (* adv_step_intermediate *)
    eexists. cbn. split.
    + reflexivity.
    + by eapply adv_step_intermediate.
  - (* adv_step_child: efs1 ++ e :: efs2 = Val w :: efs. Prim_step on e
       requires e is not a value, so efs1 starts with [Val w]. *)
    match goal with
    | H : prim_step _ _ _ _ _ _ _ |- _ => rename H into Hps
    end.
    rename efs1 into efs1_h.
    match goal with
    | H : context [efs1_h ++ _ :: _] |- _ => rename H into Hef_eq
    end.
    destruct efs1_h as [|e_h efs1']; cbn in Hef_eq.
    + (* efs1 = [], so e = Val w. Contradiction with prim_step. *)
      injection Hef_eq as Heqe _.
      apply prim_step_not_val in Hps.
      rewrite Heqe in Hps. cbn in Hps. discriminate.
    + (* efs1 = e_h :: efs1', so e_h = Val w and efs1' ++ e :: efs2 = efs. *)
      injection Hef_eq as <- Hefs_eq.
      eexists. cbn. split.
      * reflexivity.
      * rewrite -Hefs_eq. by eapply adv_step_child.
  - (* adv_step_return *)
    eexists efs. cbn. split; first done. by apply adv_step_return.
Qed.

Lemma adv_steps_drop_value_one_prefix (op obj : val) (valid_request : val → Prop)
    (w : val) π efs σ config' ts :
  adv_steps op obj valid_request (Config π (Val w :: efs) σ) config' ts →
  ∃ efs', config'.(config_childThread) = Val w :: efs' ∧
    adv_steps op obj valid_request (Config π efs σ)
      (Config config'.(config_pendingOp) efs' config'.(config_state)) ts.
Proof.
  intros Hsteps.
  remember (Config π (Val w :: efs) σ) as cfg0 eqn:Hcfg0.
  revert π efs σ Hcfg0.
  induction Hsteps as [cfg | cfg0 cfg1 cfg2 ts1 ts2 Hstep1 Hsteps2 IH]
    => π0 efs0 σ0 Hcfg0.
  - rewrite Hcfg0. eexists efs0. cbn. split; first done. constructor.
  - subst cfg0.
    apply adv_step_drop_value_one_prefix in Hstep1
      as (efs1 & Heq1 & Hstep1').
    destruct cfg1 as [π1 efs1_full σ1]. cbn in Heq1. subst efs1_full.
    destruct (IH π1 efs1 σ1 eq_refl) as (efs_final & Heq_final & Hsteps_final).
    eexists efs_final. split; first exact Heq_final.
    eapply adv_steps_cons; eassumption.
Qed.

Lemma adv_steps_drop_value_prefix (op obj : val) (valid_request : val → Prop)
    vs π efs σ config' ts :
  Forall (λ e : expr, ∃ w, e = Val w) vs →
  adv_steps op obj valid_request (Config π (vs ++ efs) σ) config' ts →
  ∃ efs', config'.(config_childThread) = vs ++ efs' ∧
    adv_steps op obj valid_request (Config π efs σ)
      (Config config'.(config_pendingOp) efs' config'.(config_state)) ts.
Proof.
  revert config' efs.
  induction vs as [|e vs IH] => config' efs Hvs Hsteps.
  - cbn in Hsteps. eexists config'.(config_childThread). cbn. split; first done.
    destruct config'. cbn. exact Hsteps.
  - rewrite Forall_cons in Hvs. destruct Hvs as [[w ->] Hvs].
    cbn in Hsteps.
    apply adv_steps_drop_value_one_prefix in Hsteps
      as (efs1 & Heq1 & Hsteps1).
    destruct (IH (Config config'.(config_pendingOp) efs1 config'.(config_state))
                 efs Hvs Hsteps1) as (efs' & Heq' & Hsteps').
    eexists efs'. cbn in Heq', Hsteps'. split.
    + rewrite Heq1. cbn. by rewrite Heq'.
    + exact Hsteps'.
Qed.
