(** This development originally
    targeted Iris's [heap_lang]; this version retargets it to MizzleLang,
    which required several non-trivial changes:

    - [encodable.v] is dropped — the original [Encodable trace]
      instance encoded events as [InjLV]/[InjRV]/pair, which don't
      exist in MizzleLang. We omit the encoding entirely; MizzleLang programs that
      emit traces will use their own conventions (e.g. the pairs of
      integers that [test/hw1_traced.v] logs through [stdlib/trace.v]).
    - The original [pure_logic/adequacy.v] dependency is dropped —
      its [adequate_nofork] is parametric in Iris's [language] type
      class, but MizzleLang has its own semantics ([mizzle.lang.semantics])
      and isn't an Iris [language]. We inline an analogue
      [adequate_nofork] stated against MizzleLang's [silent_step] /
      [not_stuck] primitives.
    - [adv_step] threads MizzleLang's extra [tid : thread_id] argument
      through every [prim_step] call, since MizzleLang's [prim_step] takes
      a thread id where heap_lang's does not.
    - [config_not_stuck] uses [Foralli] (with the slot index as
      [tid]) rather than [Forall], because MizzleLang's [not_stuck] takes
      a [tid].
    - [erased_step] becomes MizzleLang's [silent_step], and the heap_lang
      state field access [σ.(heap)] becomes [σ.(state_heap)]; there is
      no counterpart to [σ.(used_proph_id)], the language tracking
      no such set.
    - [adv_step_heap_subdom] originally went through heap_lang's
      [prim_step_heap_subdom]. There is no equivalent, so we
      prove an analogue by case analysis on [base_step] and lift
      to [prim_step]. *)

