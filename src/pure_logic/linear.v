  call_of_tag ts τ = Some x ∨ call_of_tag ts τ = None.
Proof.
  destruct x as [i t']. rewrite /call_of_tag.
  intros Hcot. rewrite list_find_app_Some in Hcot.
  destruct Hcot as [? | (_ & ? & _)]; auto.
Qed.

Lemma call_of_tag_snoc_None t ts τ :
