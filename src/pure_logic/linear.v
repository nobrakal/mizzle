(** MizzleLang doesn't fit Iris's [language] type class, so the original use of
    [adequate_nofork] from [pure_logic.adequacy] (which is parametric in
    Iris's [language]) doesn't apply directly. We instead inline a
    record with the same fields, restated against MizzleLang's primitives. *)
Record adequate_nofork (e1 : expr) (σ1 : state) (φ : val → state → Prop) := {
  adequate_nofork_nofork t2 σ2 :
    rtc silent_step ([e1], σ1) (t2, σ2) → length t2 = 1;
  adequate_nofork_result t2 σ2 v2 :
    rtc silent_step ([e1], σ1) (Val v2 :: t2, σ2) → φ v2 σ2;
  adequate_nofork_not_stuck t2 σ2 e2 i :
    rtc silent_step ([e1], σ1) (t2, σ2) →
    t2 !! i = Some e2 → not_stuck i e2 σ2
}.

(** The mathematical model of a data structure exposing a single operation, where:
  - [f s v s'] specifies that calling the operation on a structure at state [s]
    with argument [v] results in an updated state [s'];
  - [r s v v'] specifies that calling the operation on a structure at state [s]
    with argument [v] produces a result value [v']. *)
Class model := {
  S : Type;
  s_init : S;
  valid_request : val → Prop;
  request_response : S → val → S → val → Prop;
}.

Global Instance S_inhabited `{M : model} : Inhabited S := populate s_init.

(** A formal definition of linearizability of a library.
  Birkedal et al. [2021] has formalized the notation of lineariability as trace
  property. However, to migrate their definition to a library, we need a client
  to generate some traces. We introduce the notion of most adversarial client,
  and define that a library is linearizable iff the trace of using this library
  generated by a most adversarial client is lineariable. *)

(* A trace is tagged by a unique ID τ. *)
Inductive trace : Set :=
  | Call (request : val)
  | Lin (request result : val)
  | Ret (result : val).

Definition is_call t :=
  if t is Call _ then True else False.

Definition is_lin t :=
  if t is Lin _ _ then True else False.

Definition is_ret t :=
  if t is Ret _ then True else False.

Global Instance trace_eqdecision : EqDecision trace.
Proof. solve_decision. Defined.

Global Instance is_call_decide t : Decision (is_call t).
Proof. destruct t; simpl; apply _. Defined.

Global Instance is_lin_decide t : Decision (is_lin t).
Proof. destruct t; simpl; apply _. Defined.

Global Instance is_ret_decide t : Decision (is_ret t).
Proof. destruct t; simpl; apply _. Defined.

